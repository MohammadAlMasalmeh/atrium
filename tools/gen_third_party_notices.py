MIT_BODY = HEADER[HEADER.index('Permission is hereby granted'):].rstrip() + '\n'


def metadata(target):
    command = ['cargo', 'metadata', '--format-version', '1', '--locked', '--offline',
               '--filter-platform', target]
    return json.loads(subprocess.run(command, cwd=ROOT, check=True, capture_output=True).stdout)


def reachable(meta):
    """Return {package id: shipped}; shipped is False for build scripts' and proc macros' crates."""
    packages = {p['id']: p for p in meta['packages']}
    nodes = {n['id']: n for n in meta['resolve']['nodes']}
    is_macro = lambda pid: any('proc-macro' in t['kind'] for t in packages[pid]['targets'])
    result = {}
    stack = [(meta['resolve']['root'], True)]
    while stack:
        pid, shipped = stack.pop()
        shipped = shipped and not is_macro(pid)
        if result.get(pid) is True or (pid in result and not shipped):
            continue
        result[pid] = shipped
        for dep in nodes[pid]['deps']:
            kinds = {k['kind'] for k in dep['dep_kinds']}
            if None in kinds:
                stack.append((dep['pkg'], shipped))
            if 'build' in kinds:
                stack.append((dep['pkg'], False))
    del result[meta['resolve']['root']]
    return result, packages


def alternatives(expression):
    """SPDX expression as a list of alternatives, each a set of licenses that all apply."""
    tokens = re.findall(r'\(|\)|[^\s()]+', expression.replace('/', ' OR '))
    pos = 0

    def parse_or():
        nonlocal pos
        result = parse_and()
        while pos < len(tokens) and tokens[pos] == 'OR':
            pos += 1
            result = result + parse_and()
        return result

    def parse_and():
        nonlocal pos
        result = parse_atom()
        while pos < len(tokens) and tokens[pos] == 'AND':
            pos += 1
            right = parse_atom()
            result = [a | b for a in result for b in right]
        return result

    def parse_atom():
        nonlocal pos
        token = tokens[pos]
        pos += 1
        if token == '(':
            result = parse_or()
            pos += 1
            return result
        if pos < len(tokens) and tokens[pos] == 'WITH':
            token = f'{token} WITH {tokens[pos + 1]}'
            pos += 2
        return [frozenset([token])]

    return parse_or()


def review(expression):
    """None when a common permissive choice exists, else a short reason."""
    if not expression:
        return 'no license declared'
    options = alternatives(expression)
    if any(option <= COMMON for option in options):
        return None
    best = min(options, key=lambda o: len(o - COMMON))
    unusual = sorted(best - COMMON)
    kind = 'copyleft' if any(COPYLEFT.match(l) for l in unusual) else 'uncommon'
    return f'{kind}: {", ".join(unusual)}'


NOTES = {
    'MPL-2.0': 'MPL-2.0 is a file-level copyleft. Using the unmodified crate is allowed in a '
               'differently licensed app, but its source must stay available (it is published '
               'on crates.io) and modifications to its files must be released under MPL-2.0.',
    'CDLA-Permissive-2.0': 'Data license for the Mozilla root certificate list; the license text '
                           'must accompany the data.',
    'Unicode-3.0': 'Permissive Unicode data license; the license text must accompany the data.',
    'bzip2-1.0.6': 'Permissive BSD-style license of bzip2.',
}


def collect():
    crates = {}
    for target in TARGETS:
        found, packages = reachable(metadata(target))
        for pid, shipped in found.items():
            package = packages[pid]
            key = (package['name'], package['version'])
            entry = crates.setdefault(key, {'package': package, 'shipped': False})
            entry['shipped'] |= shipped
    return [crates[k] for k in sorted(crates)]


def license_files(package):
    directory = Path(package['manifest_path']).parent
    names = sorted(f.name for f in directory.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
    if package.get('license_file'):
        names.append(package['license_file'])
    files = []
    for name in dict.fromkeys(names):
        text = (directory / name).read_text(encoding='utf-8', errors='replace')
        files.append((name, '\n'.join(line.rstrip() for line in text.strip().splitlines()) + '\n'))
    return files


def fallback_text(package):
    holders = ', '.join(re.sub(r'\s*<[^>]*>', '', a) for a in package['authors']) \
        or f'the {package["name"]} contributors'
    return (f'MIT License\n\nCopyright (c) {holders}\n\n{MIT_BODY}')


def build():
    crates = collect()
    shipped = [c for c in crates if c['shipped']]
    flagged, reconstructed, texts = [], [], {}
    for crate in crates:
        package = crate['package']
        ident = f'{package["name"]} {package["version"]}'
        reason = review(package['license'])
        if reason:
            flagged.append((ident, package['license'], reason, crate['shipped']))
        files = license_files(package)
        if not files:
            reconstructed.append(ident)
            files = [('(no license file in the published crate; MIT text reconstructed from its '
                      'license field and authors)', fallback_text(package))]
        for name, text in files:
            texts.setdefault(text, []).append(f'{ident} ({name})')

    out = [HEADER, '\n3. Rust crates\n']
    out.append(textwrap.fill(
        f'{len(shipped)} crates are compiled into the app and {len(crates) - len(shipped)} more are '
        'used only at build time (build scripts and procedural macros). '
        f'Targets: {", ".join(TARGETS)}; default features.', 79) + '\n')
    out.append('\nLicense review (copyleft or uncommon licenses, grouped by license):\n')
    groups = {}
    for ident, expression, reason, is_shipped in flagged:
        groups.setdefault(reason, []).append(ident + ('' if is_shipped else ' [build time]'))
    for reason, idents in sorted(groups.items(), key=lambda g: (not g[0].startswith('copyleft'), g[0])):
        out.append(f'  - {reason}\n')
        for spdx, note in NOTES.items():
            if spdx in reason:
                out.append(textwrap.fill(note, 79, initial_indent='    ', subsequent_indent='    ') + '\n')
        out.append(textwrap.fill(', '.join(idents), 79, initial_indent='    Crates: ',
                                 subsequent_indent='    ') + '\n')
    if reconstructed:
        out.append('\nThese crates publish no license file; the MIT text below was reconstructed '
                   'from\ntheir license field and authors. Check upstream before relying on it:\n')
        out.append(''.join(f'  - {ident}\n' for ident in reconstructed))
    out.append('\nCrate                                             Version              License\n')
    for crate in crates:
        package = crate['package']
        suffix = '' if crate['shipped'] else '  [build time]'
        out.append(f'{package["name"]:<50}{package["version"]:<21}{package["license"] or "?"}{suffix}\n')
        if package.get('repository'):
            out.append(f'    {package["repository"]}\n')
    out.append('\n4. License texts\n\nEach text is printed once, followed by the crates that ship it.\n')
    for text, users in sorted(texts.items(), key=lambda item: item[1][0]):
        out.append('\n' + '=' * 79 + '\nUsed by: ' + '\n         '.join(users) + '\n' + '-' * 79 + '\n')
        out.append(text)
    return ''.join(out), flagged, reconstructed, len(shipped), len(crates)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if the committed file is out of date')
    parser.add_argument('--report', action='store_true', help='print the review without writing')
    args = parser.parse_args()
    text, flagged, reconstructed, shipped, total = build()
    print(f'{shipped} crates compiled in, {total - shipped} build-time only', file=sys.stderr)
    for ident, expression, reason, is_shipped in flagged:
        if args.report or not reason.startswith('uncommon: Unicode-3.0'):
            print(f'FLAG {ident}: {expression} ({reason}{"" if is_shipped else ", build time only"})', file=sys.stderr)
    print(f'{len(reconstructed)} crates publish no license file: {", ".join(reconstructed)}', file=sys.stderr)
    if args.report:
        return 0
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ''
        if current != text:
            print(f'{OUTPUT.name} is out of date; run tools/gen_third_party_notices.py', file=sys.stderr)
            return 1
        print(f'{OUTPUT.name} is up to date', file=sys.stderr)
        return 0
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT} ({len(text):,} bytes)', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
