#!/usr/bin/env python3
"""Regenerate THIRD-PARTY-NOTICES.txt from Cargo.lock.

Uses `cargo metadata` for the macOS targets, includes every crate reachable from
the app with default features, copies each crate's license and notice files
verbatim (identical texts are printed once), and flags copyleft or unusual
licenses. `--check` exits 1 when the committed file is out of date.

    python3 tools/gen_third_party_notices.py            # rewrite the file
    python3 tools/gen_third_party_notices.py --check    # verify it is current
    python3 tools/gen_third_party_notices.py --report   # print only the review
"""
import argparse
import json
import os
import re
import subprocess
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'THIRD-PARTY-NOTICES.txt'
TARGETS = ['aarch64-apple-darwin', 'x86_64-apple-darwin']
LICENSE_FILE = re.compile(r'^(licen[sc]e|copying|notice|copyright|unlicense)([-._ ].*)?$', re.I)

# Permissive licenses that only require keeping the notice and license text.
COMMON = {
    'MIT', 'Apache-2.0', 'Apache-2.0 WITH LLVM-exception', 'BSD-2-Clause', 'BSD-3-Clause',
    'ISC', 'Zlib', '0BSD', 'Unlicense', 'BSL-1.0', 'CC0-1.0',
}
COPYLEFT = re.compile(r'^(MPL|LGPL|GPL|AGPL|EPL|CDDL|EUPL|OSL|CECILL)', re.I)

